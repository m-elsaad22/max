def article(intro: str, sections: list[tuple[str, str, list[str] | None]], faqs: list[tuple[str, str]] | None = None) -> str:
    parts = [f"<p>{intro}</p>"]
    for title, body, bullets in sections:
        parts.append(f"<h2>{title}</h2>")
        parts.append(f"<p>{body}</p>")
        if bullets:
            parts.append("<ul>" + "".join(f"<li>{b}</li>" for b in bullets) + "</ul>")
    if faqs:
        parts.append("<h2>أسئلة متكررة</h2>")
        for q, a in faqs:
            parts.append(f"<h3>{q}</h3><p>{a}</p>")
    parts.append(CTA)
    return "\n".join(parts)


