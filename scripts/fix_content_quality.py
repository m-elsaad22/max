def update_post(url, user, password, pid, *, title=None, content=None, excerpt=None, featured=None):
    cmd = f"post update {pid}"
    if title:
        cmd += f" --post_title='{title}'"
    if content:
        cmd += f" --post_content_base64={b64(content)}"
    if excerpt:
        cmd += f" --post_excerpt='{excerpt}'"
    log_cli(f"update {pid}", cli(url, user, password, cmd, confirm=True))
    if featured:
        try:
            rest(url, user, password, f"/wp/v2/posts/{pid}", method="POST", payload={"featured_media": featured})
        except Exception:
            try:
                rest(url, user, password, f"/wp/v2/pages/{pid}", method="POST", payload={"featured_media": featured})
            except Exception:
                try:
                    rest(url, user, password, f"/wp/v2/services/{pid}", method="POST", payload={"featured_media": featured})
                except Exception as exc:
                    print("featured fail", pid, exc)


def set_robots_canonical(url, user, password, pid, canonical: str, noindex: bool):
    if noindex:
        log_cli(
            f"robots {pid}",
            cli(
                url,
                user,
                password,
                f'post meta update {pid} rank_math_robots ["noindex","follow"] --format=json --force',
                confirm=True,
            ),
        )
    log_cli(
        f"canon {pid}",
        cli(
            url,
            user,
            password,
            f"post meta update {pid} rank_math_canonical_url {canonical} --force",
            confirm=True,
        ),
    )


